/**
 * Legacy data migration: import data from the original Madhushala Pro SQL
 * Server database into this rebuild, driven from the admin UI.
 *
 * Three portable source formats are accepted (all produced from the legacy
 * machine without touching it from here):
 *
 *   1. JSON bundle   - { company, year, tables: { tableName: [row, ...] } }
 *   2. SQL dump      - the T-SQL `INSERT [dbo].[table] (...) VALUES (...)` text
 *                      (e.g. generated by sqlcmd / the SMO scripter)
 *   3. CSV           - one CSV per table (header row = column names)
 *
 * Every run is a two-step flow: `analyze` (a dry run that reports what would
 * happen) then `apply` (which writes). Both are recorded in tbl_MigrationBatch
 * so the admin has an auditable history.
 *
 * Only tables in the MIGRATABLE registry can be written, and only columns that
 * exist in the target SQLite schema are used - anything else is reported and
 * ignored. Nothing here is destructive: rows are inserted, or updated in place
 * when their primary key already exists. No table is ever deleted or truncated.
 */

