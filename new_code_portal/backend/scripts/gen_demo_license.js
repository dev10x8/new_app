#!/usr/bin/env node
// Generate the DEMO licence that ships inside the desktop app, plus the pinned
// vendor public key the app verifies licences with.
//
//   npm run gen-demo-license            # writes into ../new_code/backend/src/license/
//   npm run gen-demo-license -- --days 60
//
// The demo is a normal vendor-signed licence, except its term is RELATIVE: it
// carries `demo_days` and empty valid_from/valid_until, so the desktop starts
// the 90-day clock on the machine at first activation rather than at build
// time. It is unbound (machine_hash: ""), so the app binds it to the local
// machine fingerprint when it activates.
//
// The private key never leaves the portal; the app only gets the public key and
// this signed blob. Re-run this after setting PORTAL_LICENSE_KEY for production
// so the demo is signed by the production key the app pins.
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { sign, publicKeyBase64, usingProductionKey } from '../src/services/license.js';
import { sealPublicKey, usingProductionKey as sealProd } from '../src/services/seal.js';
import { all } from '../src/db/index.js';
import { openDatabase } from '../src/db/index.js';
import { config } from '../src/config.js';

const here = dirname(fileURLToPath(import.meta.url));
const outDir = resolve(here, '..', '..', '..', 'new_code', 'backend', 'src', 'license');

const argDays = (() => {
  const i = process.argv.indexOf('--days');
  return i >= 0 ? Number(process.argv[i + 1]) : 0;
})();
const demoDays = Number.isFinite(argDays) && argDays > 0 ? argDays : 90;

// Entitlements: every module in the catalogue, so a demo can explore everything.
let entitlements = [];
try {
  const db = openDatabase(config.dbFile);
  entitlements = all(db, 'SELECT code FROM modules ORDER BY sort').map((r) => r.code);
} catch {
  entitlements = [];
}

const payload = {
  v: 2,
  kind: 'demo',
  license_id: 'VL-DEMO-0001',
  business_code: 'DEMO',
  legalname: 'VanijLiquor Demo',
  gstin: '',
  plan: 'premium',
  period: 'demo',
  entitlements,
  machine_hash: '',
  seats: 1,
  grace_days: 15,
  offline_limit_days: demoDays,
  demo_days: demoDays,
  valid_from: '',
  valid_until: '',
  issued_at: new Date().toISOString(),
  issuer: config.issuer,
};

const signed = sign(payload);
const file = {
  format: 'vanijliquor-license',
  version: 2,
  kind: 'demo',
  license_id: payload.license_id,
  demo_days: demoDays,
  payload,
  signature: signed.signature,
  public_key: signed.publicKey,
  verify: 'Ed25519 over canonical JSON of payload; verify with the PINNED vendor key.',
};

mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, 'demo.vlic'), JSON.stringify(file, null, 2) + '\n');

const vendor = `// Generated by new_code_portal/backend/scripts/gen_demo_license.js — do not edit by hand.
//
// The vendor's Ed25519 public key (SPKI, base64). The desktop app verifies every
// licence against THIS key, so it must match the portal that issued the licence
// (PORTAL_LICENSE_KEY). Regenerate after rotating the signing key.
//
// production: ${usingProductionKey()}
export const VENDOR_PUBLIC_KEY = '${publicKeyBase64()}';
export const DEMO_LICENSE_FILE = 'demo.vlic';
export const DEMO_DAYS = ${demoDays};

// The vendor's RSA PUBLIC key (SPKI, base64) used to SEAL licence records at
// rest. The app encrypts its stored licence with this key; only the portal
// (holding the matching private key, PORTAL_SEAL_KEY) can unseal it. Including
// it in the installer is safe — it is a public key — and it means the sealed
// copy on every customer's disk is readable by the vendor alone.
//
// production: ${sealProd()}
export const VENDOR_SEAL_KEY = '${sealPublicKey()}';
`;
writeFileSync(join(outDir, 'vendor.js'), vendor);

console.log(`demo licence  -> ${join(outDir, 'demo.vlic')}`);
console.log(`vendor key    -> ${join(outDir, 'vendor.js')}`);
console.log(`  days=${demoDays}  modules=${entitlements.length}  production=${usingProductionKey()}`);
if (!usingProductionKey()) {
  console.log('  NOTE: signed with the DEVELOPMENT key. Set PORTAL_LICENSE_KEY and re-run for production.');
}
